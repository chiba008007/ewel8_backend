    public function getEAIA(Request $request)
    {
        $loginUser = auth()->user();
        $examId = $loginUser->id;
        $testpartsId = $request->testparts_id;

        // 最新の受検データを取得する
        $last = ExamEaia::where('testparts_id', $testpartsId)
            ->where('exam_id', $examId)
            ->latest('id')
            ->first();

        if (!$last) {
            return response(null, 200);
        }

        // 各ページで使用する最後の回答番号
        $pageEndKeys = [
            1 => 7,
            2 => 14,
            3 => 21,
            4 => 33,
            5 => 41,
            6 => 45,
            7 => 48,
            8 => 52,
            9 => 54,
            10 => 59,
            11 => 63,
            12 => 68,
            13 => 72,
            14 => 75,
            15 => 78,
            16 => 81,
            17 => 84,
            18 => 87,
            19 => 90,
            20 => 93,
            21 => 102,
            22 => 109,
            23 => 114,
            24 => 119,
            25 => 123,
            26 => 127,
            27 => 132,
            28 => 135,
            29 => 138,
            30 => 143,
        ];

        $currentPage = 1;
        $startKey = 1;

        foreach ($pageEndKeys as $page => $endKey) {
            // このページに未回答があるか確認する
            for ($i = $startKey; $i <= $endKey; $i++) {
                if ($last->{'q' . $i} === null) {
                    $currentPage = $page;
                    break 2;
                }
            }

            // このページが完了していれば次ページへ進める
            $currentPage = $page + 1;
            $startKey = $endKey + 1;
        }

        $last->current_page = min($currentPage, 32);

        return response($last, 200);
    }

    public function setEAIA(Request $request)
    {
        $loginUser = auth()->user();

        try {
            DB::transaction(function () use ($request, $loginUser) {
                // テスト時間を取得
                $timelimit = testparts::where('test_id', $loginUser->test_id)
                    ->where('code', self::CODE)
                    ->value('timelimit');

                // 既存の有効ステータスを無効化
                ExamEaia::where('exam_id', $loginUser->id)
                    ->where('status', 1)
                    ->update(['status' => 0]);

                // 新しい受検データを作成
                ExamEaia::create([
                    'testparts_id' => $request->testparts_id,
                    'exam_id'      => $loginUser->id,
                    'status'       => 1,
                    'starttime'    => now(),
                    'limittime'    => now()->addMinutes($timelimit),
                ]);
            });

            Log::info('EAIA開始成功', [
                'exam_id' => $loginUser->id,
                'test_id' => $loginUser->test_id,
                'ip' => $request->ip(),
            ]);

            return response('success', 200);

        } catch (\Throwable $e) {
            Log::error('EAIA開始失敗', [
                'exam_id' => $loginUser->id ?? null,
                'message' => $e->getMessage(),
                'line' => $e->getLine(),
                'ip' => $request->ip(),
            ]);

            return response('error', 500);
        }
    }

    public function editEAIA(Request $request)
    {

        /** @var \App\Models\Exam $user */
        $user = auth()->user();

        // 認証済みの受検者ID
        $exam_id = $user->id;
        $testparts_id = $request->testparts_id;

        Log::info('EAIA検査回答登録開始', [
            'exam_id' => $exam_id,
            'testparts_id' => $testparts_id,
            'page' => $request->page,
            'ip' => $request->ip(),
        ]);

        try {
            DB::transaction(function () use ($request, $exam_id, $testparts_id) {
                // 最新の受検データを取得
                $exam = ExamEaia::where('testparts_id', $testparts_id)
                    ->where('exam_id', $exam_id)
                    ->latest('id')
                    ->firstOrFail();

                // 2ページ目で開始時刻を更新
                if ((int)$request->page === 2) {
                    $exam->starttime = now();
                }

                // 回答を登録
                foreach ($request->selectPoint as $key => $value) {
                    $exam['q' . $key] = $value;
                }

                $exam->save();
                // 最終ページなら採点・完了処理
                if ((int)$request->page === 31) {

                    $this->getArrayPoint();
                    $score = [];

                    for ($i = 1; $i <= 143; $i++) {
                        $score[$i] = $exam['q' . $i];
                    }

                    $array_result = $this->getEAIAResult($score);

                    $exam->update([
                        'sougo'    => $array_result['sougo'],
                        'yomitori' => $array_result['yomitori'],
                        'rikai'    => $array_result['rikai'],
                        'sentaku'  => $array_result['sentaku'],
                        'kirikae'  => $array_result['kirikae'],
                        'jyoho'    => $array_result['jyoho'],
                        'endtime'  => now(),
                    ]);
                    Log::info('EAIA採点結果保存成功', [
                        'exam_id' => $exam_id,
                        'testparts_id' => $testparts_id,
                        'exambea_id' => $exam->id,
                    ]);

                    examfins::complete($exam_id, $testparts_id);
                    exam::setEndTime();

                    Log::info('受検者終了時刻更新成功', [
                        'exam_id' => $exam_id,
                    ]);

                    exam::sendRemainMail($request);
                    Log::info('残数メール処理成功', [
                        'exam_id' => $exam_id,
                        'testparts_id' => $testparts_id,
                    ]);

                }
            });

            return response('success', 200);

        } catch (\Throwable $e) {
            Log::error('EAIA検査回答登録失敗', [
                'exam_id' => $exam_id,
                'testparts_id' => $testparts_id,
                'page' => $request->page,
                'message' => $e->getMessage(),
                'line' => $e->getLine(),
                'ip' => $request->ip(),
            ]);

            return response('error', 500);
        }
    }

    public function getEAIAResult($rlt)
    {
        $array = $this->array_calc;
        $array_vf = $this->array_vf;

        $total = 0;
        $read = 0;
        $kirikae = 0;
        $rikai = 0;
        $select = 0;
        $info1 = 0;
        $info2 = 0;

        foreach ($rlt as $i => $v) {
            $score[$i] = $array[$i][$v];
            $total += $array[$i][$v];

            // 読み取り力
            if ($i >= 1 && $i <= 21) {
                $read += $array[$i][$v];
            }

            if ($i >= 73 && $i <= 93) {
                $read += $array[$i][$v];
            }

            // 切り替え
            if ($i >= 22 && $i <= 41) {
                $kirikae += $array[$i][$v];
            }

            if ($i >= 94 && $i <= 109) {
                $kirikae += $array[$i][$v];
            }

            // 理解
            if ($i >= 42 && $i <= 59) {
                $rikai += $array[$i][$v];
            }

            if ($i >= 110 && $i <= 123) {
                $rikai += $array[$i][$v];
            }

            // 選択
            if ($i >= 60 && $i <= 72) {
                $select += $array[$i][$v];
            }

            if ($i >= 124 && $i <= 143) {
                $select += $array[$i][$v];
            }

            // 情報のとらえ方
            if ($i == 80) {
                $info1 = $v;
            }

            if (
                $i == 73 || $i == 74 || $i == 75 ||
                $i == 77 || $i == 78 || $i == 79 ||
                $i == 81 || $i == 82 ||
                $i == 85 || $i == 86 ||
                $i == 88 || $i == 89 ||
                $i == 91 || $i == 92 || $i == 93
            ) {
                $info2 += $v;
            }
        }

        $info = $info1 - $info2 / 15;

        // 偏差値
        $sougo   = (($total - $array_vf['sougo']['ave']) * 10)
            / $array_vf['sougo']['hen'] + 50;

        $reads   = (($read - $array_vf['read']['ave']) * 10)
            / $array_vf['read']['hen'] + 50;

        $changes = (($kirikae - $array_vf['change']['ave']) * 10)
            / $array_vf['change']['hen'] + 50;

        $unders  = (($rikai - $array_vf['understand']['ave']) * 10)
            / $array_vf['understand']['hen'] + 50;

        $selects = (($select - $array_vf['select']['ave']) * 10)
            / $array_vf['select']['hen'] + 50;

        $jyoho   = (($info - $array_vf['vaias']['ave']) * 10)
            / $array_vf['vaias']['hen'] + 50;

        $sougo   = max(20.0, min(80.0, $sougo));
        $reads   = max(20.0, min(80.0, $reads));
        $changes = max(20.0, min(80.0, $changes));
        $unders  = max(20.0, min(80.0, $unders));
        $selects = max(20.0, min(80.0, $selects));
        $jyoho   = max(20.0, min(80.0, $jyoho));

        return [
            'sougo' => $sougo,
            'yomitori' => $reads,
            'rikai' => $unders,
            'sentaku' => $selects,
            'kirikae' => $changes,
            'jyoho' => $jyoho,
        ];
    }

